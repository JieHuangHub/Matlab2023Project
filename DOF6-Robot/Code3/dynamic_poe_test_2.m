%% 0) 输入：关节状态（6x1）
q   = [0, 0, 0, 0, 0, 0]';        % 关节角 (rad)
qd  = [0, 0, 0, 0, 0, 0]';        % 关节角速度
qdd = [0, 0, 0, 0, 0, 0]';        % 关节角加速度
% 修正1：重力向量符号（与Simulink保持一致，z轴正方向）
g_vec = [0, 0, 9.81]';           % 重力向量 (m/s^2)
Ftip  = [0, 0, 0, 0, 0, 0]';      % 末端外力 (6x1 Wrench)

%% 1) 几何参数 (POE 核心参数)
% 关节轴方向 w (6x1) - 修正2：检查关节轴方向（与Simulink一致）
w1 = [0; 0; 1];
w2 = [0; -1; 0];  % 修正：关节2轴方向取反（原[0;1;0]）
w3 = [0; -1; 0];  % 修正：关节3轴方向取反（原[0;1;0]）
w4 = [1; 0; 0];
w5 = [0; -1; 0];  % 修正：关节5轴方向取反（原[0;1;0]）
w6 = [1; 0; 0];

% 关节轴上一点 r (空间位置) - 保持不变
r1 = [0; 0; 0];
r2 = [0.035; 0; 0.1245];
r3 = [0.035; 0; 0.1245 + 0.146];          % [0.035, 0, 0.2705]
r4 = [0.035; 0; 0.1245 + 0.146 + 0.052];  % [0.035, 0, 0.3225]
r5 = [0.035 + 0.117; 0; 0.3225];          % [0.152, 0, 0.3225]
r6 = [0.035 + 0.117 + 0.0775; 0; 0.3225]; % [0.2295, 0, 0.3225]

%% 2) 构造空间螺旋轴 Slist (6x6)
% 修正3：螺旋轴线速度分量符号（根据InverseDynamics函数接口调整）
% 若InverseDynamics函数要求 Sv = w×r，则用cross(w, r)；若要求 Sv = r×w，则用-cross(w, r)
% 这里先按Simulink标准公式：S = [w; r×w] = [w; -cross(w, r)]（保持原公式，但修正关节轴方向）
S1 = [w1; -cross(w1, r1)];
S2 = [w2; -cross(w2, r2)];
S3 = [w3; -cross(w3, r3)];
S4 = [w4; -cross(w4, r4)];
S5 = [w5; -cross(w5, r5)];
S6 = [w6; -cross(w6, r6)];
Slist = [S1, S2, S3, S4, S5, S6];

%% 3) 构造 Mlist (4x4x7) 相对位姿链 - 修正4：旋转矩阵符号（与Simulink一致）
M1 = [
    1.0000,  0.0000,  0.0000,  0.0350;
    0.0000,  0.0000, -1.0000,  0.0000;  % 修正：第三列符号取反
    0.0000,  1.0000,  0.0000,  0.1245;  % 修正：第二列符号取反
    0.0000,  0.0000,  0.0000,  1.0000 ];

M2 = [
    0.0000, -1.0000,  0.0000,  0.0000;  % 修正：第二列符号取反
    1.0000,  0.0000,  0.0000, -0.1460;  % 修正：第一列符号取反
    0.0000,  0.0000,  1.0000,  0.0000;
    0.0000,  0.0000,  0.0000,  1.0000 ];

M3 = [
    1.0000,  0.0000,  0.0000,  0.0520;
    0.0000,  0.0000, -1.0000,  0.0000;  % 修正：第三列符号取反
    0.0000,  1.0000,  0.0000,  0.0000;  % 修正：第二列符号取反
    0.0000,  0.0000,  0.0000,  1.0000 ];

M4 = [
    1.0000,  0.0000,  0.0000,  0.0000;
    0.0000,  0.0000,  1.0000,  0.0000;  % 修正：第三列符号取反
    0.0000, -1.0000,  0.0000,  0.1170;  % 修正：第二列符号取反
    0.0000,  0.0000,  0.0000,  1.0000 ];

M5 = [
    1.0000,  0.0000,  0.0000,  0.0000;
    0.0000,  0.0000, -1.0000,  0.0000;  % 修正：第三列符号取反
    0.0000,  1.0000,  0.0000,  0.0000;  % 修正：第二列符号取反
    0.0000,  0.0000,  0.0000,  1.0000 ];

M6 = [
    1.0000,  0.0000,  0.0000,  0.0000;
    0.0000,  1.0000,  0.0000,  0.0000;
    0.0000,  0.0000,  1.0000,  0.0775;
    0.0000,  0.0000,  0.0000,  1.0000 ];

M7 = [
    1.00000,  0.00000,  0.00000,  0.00000;
    0.00000,  1.00000,  0.00000,  0.00000;
    0.00000,  0.00000,  1.00000,  0.00000;
    0.00000,  0.00000,  0.00000,  1.00000 ];

Mlist = cat(3, M1, M2, M3, M4, M5, M6, M7);

%% 4) 质量与空间惯量 Glist (6x6x6) - 保持不变
m_1   = 0.416; Ixx_1 = 0.000; Iyy_1 = 0.000; Izz_1 = 0.000;
m_2   = 2.462; Ixx_2 = 0.001; Iyy_2 = 0.008; Izz_2 = 0.007;
m_3   = 0.977; Ixx_3 = 0.001; Iyy_3 = 0.001; Izz_3 = 0.001;
m_4   = 0.782; Ixx_4 = 0.001; Iyy_4 = 0.001; Izz_4 = 0.000;
m_5   = 0.393; Ixx_5 = 0.000; Iyy_5 = 0.000; Izz_5 = 0.000;
m_6   = 0.106; Ixx_6 = 0.000; Iyy_6 = 0.000; Izz_6 = 0.000;

G1 = diag([Ixx_1, Iyy_1, Izz_1, m_1, m_1, m_1]);
G2 = diag([Ixx_2, Iyy_2, Izz_2, m_2, m_2, m_2]);
G3 = diag([Ixx_3, Iyy_3, Izz_3, m_3, m_3, m_3]);
G4 = diag([Ixx_4, Iyy_4, Izz_4, m_4, m_4, m_4]);
G5 = diag([Ixx_5, Iyy_5, Izz_5, m_5, m_5, m_5]);
G6 = diag([Ixx_6, Iyy_6, Izz_6, m_6, m_6, m_6]);
Glist = cat(3, G1, G2, G3, G4, G5, G6);

%% 5) 逆动力学计算
tau = InverseDynamics(q, qd, qdd, g_vec, Ftip, Mlist, Glist, Slist);

disp('-------------------------------------');
