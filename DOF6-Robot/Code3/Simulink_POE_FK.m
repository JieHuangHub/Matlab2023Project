function KPS44 = Simulink_POE_FK(Radian)
% Simulink_POE_FK 适配Simulink的6自由度机械臂POE正解函数（精准参数版）
% 【Simulink专用】MATLAB Function模块直接调用
% 输入:  Radian - 1×6 关节角度向量 (弧度)，Simulink输入需设为1维数组
% 输出:  KPS44 - 4×4 末端齐次变换矩阵，Simulink输出设为4×4矩阵

%% 1. 强制维度标准化（适配Simulink输入，避免维度错误）
theta = reshape(Radian, 6, 1);  % 确保关节角为6×1列向量

%% 2. 定义关节旋量轴核心参数（你的精准参数）
% 2.1 关节轴角速度方向 omega_i (单位向量，6×1列向量)
w1 = [0; 0; 1];
w2 = [0; -1; 0];
w3 = [0; -1; 0];
w4 = [1; 0; 0];
w5 = [0; -1; 0];
w6 = [1; 0; 0];

% 2.2 关节轴上一点 r_i (单位：m，6×1列向量)
r1 = [0; 0; 0];
r2 = [0.035; 0; 0.1245];
r3 = [0.035; 0; 0.1245 + 0.146];       % 0.2705
r4 = [0.035; 0; 0.1245 + 0.146 + 0.052]; % 0.3225
r5 = [0.035 + 0.117; 0; 0.3225];        % 0.152, 0, 0.3225
r6 = [0.035 + 0.117 + 0.0775; 0; 0.3225]; % 0.2295, 0, 0.3225

% 2.3 计算线速度向量 v = -w × r (旋量轴的平移部分)
v1 = -cross(w1, r1);
v2 = -cross(w2, r2);
v3 = -cross(w3, r3);
v4 = -cross(w4, r4);
v5 = -cross(w5, r5);
v6 = -cross(w6, r6);

% 2.4 构建螺旋轴列表 Slist (6×6，每列是一个旋量 S_i = [w; v])
Slist = [w1, w2, w3, w4, w5, w6;
         v1, v2, v3, v4, v5, v6];

%% 3. 零位姿态矩阵 M (home configuration，你的精准参数)
M = [ 0,  0,  1,  0.2295; 
      0, -1,  0,  0.000; 
      1,  0,  0,  0.3225; 
      0,  0,  0,  1    ];

%% 4. POE核心计算：T(θ) = e^[S1]θ1 * e^[S2]θ2 * ... * e^[S6]θ6 * M
T = eye(4);  % 初始化变换矩阵为单位矩阵
for i = 1:6
    % 提取第i个关节的旋量分量
    w = Slist(1:3, i);
    v = Slist(4:6, i);
    
    % 构建角速度叉乘矩阵 w_hat
    wx = w(1); wy = w(2); wz = w(3);
    w_hat = [   0,  -wz,   wy;
              wz,    0,  -wx;
             -wy,   wx,    0 ];
    
    % 构建se(3)李代数矩阵 [w_hat, v; 0 0 0 0]
    se3mat = [w_hat, v;
              0,  0,  0,  0];
    
    % 计算旋量指数映射 e^([S_i]θ_i)
    T = T * expm(se3mat * theta(i));
end

%% 5. 最终末端位姿矩阵 (乘零位矩阵M)
KPS44 = T * M;

end