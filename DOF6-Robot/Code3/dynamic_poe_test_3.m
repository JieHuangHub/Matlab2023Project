%% 空间惯量矩阵构造函数
function G = SpatialInertia(m, pc, Ixx, Iyy, Izz, Ixy, Ixz, Iyz)
    % 输入: 
    %   m:   质量
    %   pc:  质心位置 [x; y; z] (在连杆坐标系下)
    %   Ixx, Iyy, Izz, Ixy, Ixz, Iyz: 惯性张量分量 (关于质心)
    %
    % 输出:
    %   G: 6x6 空间惯量矩阵
    
    % 惯性张量 (关于质心)
    I_c = [Ixx, Ixy, Ixz;
           Ixy, Iyy, Iyz;
           Ixz, Iyz, Izz];
    
    % 质心的反对称矩阵
    pc_skew = skew(pc);
    
    % 空间惯量矩阵 (6x6)
    % G = [I + m*pc_skew*pc_skew',  m*pc_skew;
    %      m*pc_skew',              m*eye(3)]
    G = [I_c + m*(pc_skew * pc_skew'),  m * pc_skew;
         m * pc_skew',                   m * eye(3)];
end

function S = skew(v)
    % 反对称矩阵
    S = [0, -v(3), v(2);
         v(3), 0, -v(1);
        -v(2), v(1), 0];
end
